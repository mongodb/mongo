"""Tests for generating CI filegroups from configured Bazel targets."""

import contextlib
import io
import json
import os
import subprocess
import tempfile
import unittest
from pathlib import Path
from unittest import mock

from bazel.wrapper_hook import autogenerated_targets


class AutogeneratedTargetsTest(unittest.TestCase):
    def setUp(self) -> None:
        temporary_directory = tempfile.TemporaryDirectory()
        self.addCleanup(temporary_directory.cleanup)
        self.output_file = Path(temporary_directory.name) / "BUILD.bazel"

    @staticmethod
    def query_result(
        records: list[dict[str, str | bool | list[str]]], returncode: int = 0
    ) -> subprocess.CompletedProcess[str]:
        return subprocess.CompletedProcess(
            [], returncode, "\n".join(json.dumps(record) for record in records), "query failed"
        )

    def test_one_query_groups_compatible_targets_and_sorts_unique_labels(self) -> None:
        records = [
            {
                "label": "@//src:z_test",
                "compatible": True,
                "tags": ["mongo_unittest", "mongo_unittest_first_group", "unrelated"],
            },
            {"label": "@@//src:a_test", "compatible": True, "tags": ["mongo_unittest"]},
            {"label": "//src:a_test", "compatible": True, "tags": ["mongo_unittest"]},
            {"label": "@//src:skipped", "compatible": False, "tags": ["mongo_unittest"]},
            {"label": "@//src:unrelated", "compatible": True, "tags": ["mongo_unittest_extra"]},
        ]
        with mock.patch.object(
            autogenerated_targets.subprocess, "run", return_value=self.query_result(records)
        ) as run:
            autogenerated_targets.generate_targets(
                ["build", "--config=opt", "//:install-unittests"], "/path/bazel", self.output_file
            )

        run.assert_called_once()
        command = run.call_args.args[0]
        self.assertEqual(
            command[:4], ["/path/bazel", "cquery", "--remote_executor=", "--config=opt"]
        )
        self.assertIn("kind(extract_debuginfo_test, attr(tags,", command[4])
        self.assertIn("//src/...", command[4])
        for tag in autogenerated_targets.bazel_tags_to_autogenerate:
            self.assertIn(tag, command[4])
        content = self.output_file.read_text()
        self.assertIn(
            'filegroup(\n    name="mongo_unittest",\n    srcs=[\n'
            '        "//src:a_test",\n        "//src:z_test",\n    ],',
            content,
        )
        self.assertIn(
            'filegroup(\n    name="mongo_unittest_first_group",\n    srcs=[\n'
            '        "//src:z_test",\n    ],',
            content,
        )
        self.assertIn('name="mongo_benchmark",\n    srcs=[\n    ],', content)
        self.assertNotIn("skipped", content)
        self.assertNotIn("unrelated", content)
        self.assertEqual(content.count('"//src:a_test"'), 1)
        self.assertEqual(content.count("filegroup("), 20)

    def test_empty_query_still_creates_every_filegroup(self) -> None:
        with mock.patch.object(
            autogenerated_targets.subprocess, "run", return_value=self.query_result([])
        ) as run:
            autogenerated_targets.generate_targets(output_file=self.output_file)
        run.assert_called_once()
        content = self.output_file.read_text()
        self.assertEqual(content.count("filegroup("), 20)
        self.assertEqual(content.count("    srcs=[\n    ],"), 20)

    def test_generation_preserves_mtime_when_query_order_changes(self) -> None:
        records = [
            {"label": "@//src:z_test", "compatible": True, "tags": ["mongo_unittest"]},
            {"label": "@//src:a_test", "compatible": True, "tags": ["mongo_unittest"]},
        ]
        with mock.patch.object(
            autogenerated_targets.subprocess,
            "run",
            side_effect=[self.query_result(records), self.query_result(records[::-1])],
        ):
            autogenerated_targets.generate_targets(output_file=self.output_file)
            os.utime(self.output_file, ns=(1_000_000_000, 1_000_000_000))
            with mock.patch("builtins.open", wraps=open) as open_file:
                autogenerated_targets.generate_targets(output_file=self.output_file)
            self.assertFalse(
                any(len(call.args) > 1 and call.args[1] == "w" for call in open_file.call_args_list)
            )
            self.assertEqual(self.output_file.stat().st_mtime_ns, 1_000_000_000)

    def test_changed_content_is_written(self) -> None:
        self.output_file.write_text("old content\n")
        autogenerated_targets.write_bazel_file(["first target", "second target"], self.output_file)
        self.assertEqual(self.output_file.read_text(), "first target\n\nsecond target\n\n")

    def test_query_retries_locally_and_preserves_configuration(self) -> None:
        with (
            mock.patch.object(
                autogenerated_targets.subprocess,
                "run",
                side_effect=[self.query_result([], 1), self.query_result([])],
            ) as run,
            contextlib.redirect_stderr(io.StringIO()),
        ):
            autogenerated_targets.generate_targets(["--config=opt"], output_file=self.output_file)
        self.assertEqual(run.call_count, 2)
        first_command, retry_command = [call.args[0] for call in run.call_args_list]
        self.assertEqual(
            first_command[:4], ["bazel", "cquery", "--remote_executor=", "--config=opt"]
        )
        self.assertEqual(retry_command[:4], ["bazel", "cquery", "--config=local", "--config=opt"])
        self.assertEqual(first_command[4:], retry_command[4:])

    def test_failed_queries_preserve_existing_output(self) -> None:
        self.output_file.write_text("old content\n")
        with (
            mock.patch.object(
                autogenerated_targets.subprocess, "run", return_value=self.query_result([], 1)
            ) as run,
            contextlib.redirect_stderr(io.StringIO()),
            contextlib.redirect_stdout(io.StringIO()),
            self.assertRaises(SystemExit) as error,
        ):
            autogenerated_targets.generate_targets(output_file=self.output_file)
        self.assertEqual(error.exception.code, 1)
        self.assertEqual(run.call_count, 2)
        self.assertEqual(self.output_file.read_text(), "old content\n")


if __name__ == "__main__":
    unittest.main()
