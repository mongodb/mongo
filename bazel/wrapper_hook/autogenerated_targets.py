import json
import os
import subprocess
import sys
from collections.abc import Iterable, Sequence

bazel_tags_to_autogenerate = [
    "bsoncolumn_bm",
    "mongo_benchmark",
    "mongo_fuzzer_test",
    "mongo_integration_test",
    "mongo_unittest",
    "mongo_unittest_first_group",
    "mongo_unittest_second_group",
    "mongo_unittest_third_group",
    "mongo_unittest_fourth_group",
    "mongo_unittest_fifth_group",
    "mongo_unittest_sixth_group",
    "mongo_unittest_seventh_group",
    "mongo_unittest_eighth_group",
    "query_bm",
    "repl_bm",
    "sharding_bm",
    "sep_bm",
    "storage_bm",
    "first_half_bm",
    "second_half_bm",
]


def autogenerate_targets(args: Sequence[str], bazel: str) -> None:
    bazel_autogenerate_flag = "include_autogenerated_targets"
    output_file = os.path.join(
        "src", "mongo", "db", "modules", "enterprise", "autogenerated_targets", "BUILD.bazel"
    )
    if not any(bazel_autogenerate_flag in arg for arg in args):
        if os.path.exists(output_file):
            os.remove(output_file)
        return
    generate_targets(args, bazel, output_file)


def generate_targets(
    args: Sequence[str] = (),
    bazel: str = "bazel",
    output_file: str | os.PathLike[str] = os.path.join(
        "src", "mongo", "db", "modules", "enterprise", "autogenerated_targets", "BUILD.bazel"
    ),
) -> None:
    labels_by_tag = group_labels_by_tag(get_bazel_targets(args, bazel))
    targets = [create_target(tag, labels_by_tag[tag]) for tag in bazel_tags_to_autogenerate]
    write_bazel_file(targets, output_file)


def get_bazel_targets(args: Sequence[str], bazel: str) -> list[str]:
    # This way we mostly keep the passed config, this parsing isn't perfect
    # for the ways you can call bazel configs but this should mostly just be used in CI
    # where we control how things are called
    extra_args = [arg for arg in args if arg.startswith("--")]
    # The .cquery file is used to get info on which targets are compatible
    # with our current config. Without it dependent targets would just be skipped.
    # Restrict analysis to the same tagged rules as the individual queries.
    tags_pattern = "|".join(bazel_tags_to_autogenerate)
    query_args = [
        f"kind(extract_debuginfo_test, attr(tags, '\\b({tags_pattern})\\b', //src/...))",
        "--output=starlark",
        "--starlark:file=bazel/wrapper_hook/target_compatable.cquery",
    ]
    proc = subprocess.run(
        [bazel, "cquery", "--remote_executor="] + extra_args + query_args,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
    )
    if proc.returncode != 0:
        print(
            "WARNING: Autogenerated query failed with remote cache/downloader enabled; "
            "retrying with `--config=local`.",
            file=sys.stderr,
        )
        proc = subprocess.run(
            [bazel, "cquery", "--config=local"] + extra_args + query_args,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
        )
    if proc.returncode != 0:
        print("ERROR: Autogenerated query failed:")
        print(proc.stderr)
        sys.exit(1)
    return proc.stdout.splitlines()


def group_labels_by_tag(targets: Iterable[str]) -> dict[str, set[str]]:
    labels_by_tag: dict[str, set[str]] = {tag: set() for tag in bazel_tags_to_autogenerate}
    for target in targets:
        record = json.loads(target)
        if not record["compatible"]:
            continue
        # Bazel can print main-repository labels with either @ or @@.
        label = record["label"].lstrip("@")
        for tag in record["tags"]:
            if tag in labels_by_tag:
                labels_by_tag[tag].add(label)
    return labels_by_tag


def create_target(tag: str, labels: Iterable[str]) -> str:
    target = []
    target.append("filegroup(")
    target.append(f'    name="{tag}",')
    target.append("    srcs=[")
    for label in sorted(labels):
        target.append(f'        "{label}",')
    target.append("    ],")
    target.append("    testonly=True,")
    target.append('    visibility=["//visibility:public"],')
    target.append(")")
    return "\n".join(target)


# We default write the enterprise directory so we can access both bazel package targets
def write_bazel_file(targets: Iterable[str], output_file: str | os.PathLike[str]) -> None:
    content = "".join(target + "\n\n" for target in targets)
    try:
        with open(output_file) as buildfile:
            if buildfile.read() == content:
                return
    except FileNotFoundError:
        pass
    with open(output_file, "w") as buildfile:
        buildfile.write(content)


if __name__ == "__main__":
    generate_targets()
