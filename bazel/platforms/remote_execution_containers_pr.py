#!/usr/bin/env python3
"""
Open a PR with the remote execution container files regenerated by
bazel/platforms/remote_execution_containers_generator.py.

The generator rewrites remote_execution_containers.bzl in place, and the repin script rewrites
the dockerfiles it builds from. Both have to land on the branch for the newly pushed images to
actually be used, so the Evergreen task that runs the generator hands the results to this script
instead of leaving them in a task workspace that gets thrown away.
"""

import argparse
import json
import os
import pathlib
import sys
import time

from github import GithubException, GithubIntegration, InputGitTreeElement, Repository

CONTAINER_FILE = "bazel/platforms/remote_execution_containers.bzl"
DOCKERFILE_DIR = "bazel/remote_execution_container"
LOCKFILE = "MODULE.bazel.lock"


def chdir_to_workspace() -> None:
    """Work from the repo root, which is not the cwd under `bazel run`."""
    workspace = os.environ.get("BUILD_WORKSPACE_DIRECTORY")
    if workspace:
        os.chdir(workspace)


def is_truthy(value: str) -> bool:
    """Interpret an Evergreen expansion, which always arrives as a string."""
    return value.strip().lower() in ("true", "1", "yes")


def default_files() -> list[str]:
    """Return the container map plus every generated dockerfile."""
    dockerfiles = sorted(
        str(path) for path in pathlib.Path(DOCKERFILE_DIR).glob("*/[Dd]ockerfile") if path.is_file()
    )
    return [CONTAINER_FILE, LOCKFILE, *dockerfiles]


def lockfile_digests() -> dict[str, str]:
    """Return this repo's module extension digests from MODULE.bazel.lock.

    Only extensions defined in the main repo, whose labels start with "//", are reported.
    They are the ones the container map can invalidate; the third-party ones are noise.
    """
    lockfile = pathlib.Path(LOCKFILE)
    if not lockfile.is_file():
        return {}
    extensions = json.loads(lockfile.read_text(encoding="utf-8")).get("moduleExtensions", {})
    return {
        name: value["general"]["bzlTransitiveDigest"]
        for name, value in extensions.items()
        if name.startswith("//") and "bzlTransitiveDigest" in value.get("general", {})
    }


def print_dry_run(files: list[str]) -> None:
    """Dump what a real run would commit: the container map and the lockfile digests.

    The digests are needed alongside the map, since rewriting it invalidates the recorded
    extension digests and analysis then fails with "MODULE.bazel.lock is no longer up-to-date".
    """
    print("Dry run, not opening a PR.\n")

    container_file = pathlib.Path(CONTAINER_FILE)
    if container_file.is_file():
        print(container_file.read_text(encoding="utf-8"))
    else:
        print(f"{CONTAINER_FILE} does not exist.")

    digests = lockfile_digests()
    if digests:
        print(f"{LOCKFILE} bzlTransitiveDigest:")
        for name, digest in sorted(digests.items()):
            print(f'    "{name}": "{digest}",')
    else:
        print(f"{LOCKFILE} has no recorded extension digests.")


def restore_pem_newlines(raw_key: str) -> str:
    """Restore the newlines Evergreen's expansion storage strips from a PEM key.

    Preserves the 31 character header and 29 character footer of an RSA private key.
    """
    return raw_key[:31] + raw_key[31:-29].replace(" ", "\n") + raw_key[-29:]


def get_repository(github_owner: str, github_repo: str, app_id: str, raw_key: str):
    """Authenticate as mongo-pr-bot and return the repository.

    The project's own GitHub app is read-only on 10gen/mongo, so github.generate_token
    cannot mint a token that can push a branch or open a PR.
    """
    integration = GithubIntegration(str(int(app_id)), restore_pem_newlines(raw_key))
    installation = integration.get_repo_installation(github_owner, github_repo)
    return installation.get_github_for_installation().get_repo(f"{github_owner}/{github_repo}")


def read_containers(content: str) -> dict[str, dict[str, str]]:
    """Evaluate a remote_execution_containers.bzl and return its mapping."""
    if not content:
        return {}
    namespace: dict = {}
    exec(compile(content, CONTAINER_FILE, "exec"), {}, namespace)
    return namespace.get("REMOTE_EXECUTION_CONTAINERS", {})


def summarize_container_changes(old_content: str, new_content: str) -> str:
    """Return a markdown bullet list of the distros whose pinned container moved."""
    old = read_containers(old_content)
    new = read_containers(new_content)

    lines = []
    for distro in sorted(set(old) | set(new)):
        old_url = old.get(distro, {}).get("container-url", "")
        new_url = new.get(distro, {}).get("container-url", "")
        if old_url == new_url:
            continue
        if not old_url:
            lines.append(f"- **{distro}**: added, now `{new_url}`")
        elif not new_url:
            lines.append(f"- **{distro}**: removed")
        else:
            lines.append(
                f"- **{distro}**: `{old_url.rsplit('@', 1)[-1]}` â†’ `{new_url.rsplit('@', 1)[-1]}`"
            )

    unchanged = sorted(
        distro
        for distro in set(old) & set(new)
        if old[distro].get("container-url") == new[distro].get("container-url")
    )
    if unchanged:
        lines.append(f"- _Unchanged: {', '.join(unchanged)}_")

    return "\n".join(lines) if lines else "- No container changes"


def file_content_on_branch(repo: Repository.Repository, path: str, branch: str) -> str:
    """Return a file's content on a branch, or an empty string when it does not exist."""
    try:
        return repo.get_contents(path, ref=f"refs/heads/{branch}").decoded_content.decode()
    except GithubException as exc:
        if exc.status in (403, 404):
            return ""
        raise


def create_branch(repo: Repository.Repository, base_branch: str, new_branch: str) -> None:
    """Create the PR branch, tolerating one left behind by an earlier run."""
    try:
        sha = repo.get_branch(base_branch).commit.sha
        repo.create_git_ref(ref=f"refs/heads/{new_branch}", sha=sha)
        print(f"Created branch '{new_branch}' from '{base_branch}' at {sha}")
    except GithubException as exc:
        if exc.status == 422:
            print(f"Branch '{new_branch}' already exists, reusing it")
        else:
            raise


def main() -> int:
    parser = argparse.ArgumentParser(
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
        description=__doc__,
    )
    parser.add_argument("--github-owner", required=True, help="GitHub org/owner, e.g. 10gen.")
    parser.add_argument("--github-repo", required=True, help="GitHub repository, e.g. mongo.")
    parser.add_argument("--base-branch", required=True, help="Branch to merge into.")
    parser.add_argument("--new-branch", required=True, help="Branch to push the changes to.")
    parser.add_argument("--pr-title", required=True, help="Title for the PR.")
    parser.add_argument(
        "--file",
        action="append",
        default=[],
        metavar="PATH",
        help="File to include. May be repeated. Defaults to the container map and dockerfiles.",
    )
    parser.add_argument(
        "--dry-run",
        default="false",
        metavar="BOOL",
        help=(
            "Report what would be committed without touching GitHub. Takes a value rather than "
            "being a flag so it can be driven by an Evergreen expansion, e.g. ${is_patch}."
        ),
    )
    parser.add_argument(
        "--app-id",
        default=os.getenv("MONGO_PR_BOT_APP_ID"),
        help="mongo-pr-bot GitHub App ID.",
    )
    parser.add_argument(
        "--private-key",
        default=os.getenv("MONGO_PR_BOT_PRIVATE_KEY"),
        help="mongo-pr-bot GitHub App private key.",
    )
    args = parser.parse_args()

    chdir_to_workspace()
    files = args.file or default_files()

    if is_truthy(args.dry_run):
        print_dry_run(files)
        return 0

    if not args.app_id or not args.private_key:
        parser.error(
            "Must pass --app-id or set MONGO_PR_BOT_APP_ID, and --private-key or set "
            "MONGO_PR_BOT_PRIVATE_KEY."
        )

    repo = get_repository(args.github_owner, args.github_repo, args.app_id, args.private_key)

    # Files that differ from the base branch. Anything else is left alone so an unrelated
    # dockerfile does not get dragged into the PR.
    changed: list[tuple[str, str]] = []
    original_container_file = ""
    for path in files:
        try:
            new_content = pathlib.Path(path).read_text(encoding="utf-8")
        except FileNotFoundError:
            print(f"'{path}' does not exist locally, skipping")
            continue

        base_content = file_content_on_branch(repo, path, args.base_branch)
        if path == CONTAINER_FILE:
            original_container_file = base_content
        if base_content != new_content:
            print(f"Detected change in '{path}'")
            changed.append((path, new_content))

    if not changed:
        print("No container files changed. Skipping PR.")
        return 0

    create_branch(repo, args.base_branch, args.new_branch)
    # Creating a commit immediately after the ref can 409.
    time.sleep(5)

    # Only commit what also differs from the PR branch, so re-running against an open PR does
    # not push an empty commit every time.
    to_commit = [
        (path, content)
        for path, content in changed
        if file_content_on_branch(repo, path, args.new_branch) != content
    ]

    if to_commit:
        base_commit = repo.get_git_commit(repo.get_branch(args.new_branch).commit.sha)
        tree = repo.create_git_tree(
            [
                InputGitTreeElement(path=path, mode="100644", type="blob", content=content)
                for path, content in to_commit
            ],
            repo.get_git_tree(base_commit.sha),
        )
        message = "Update remote execution containers: " + ", ".join(path for path, _ in to_commit)
        commit = repo.create_git_commit(message, tree, [base_commit])
        repo.get_git_ref(f"heads/{args.new_branch}").edit(commit.sha)
        print(f"Committed {len(to_commit)} file(s) as {commit.sha}")
    else:
        print("PR branch already has these files. Skipping commit.")

    pulls = repo.get_pulls(
        state="open", head=f"{args.github_owner}:{args.new_branch}", base=args.base_branch
    )
    new_container_file = dict(changed).get(CONTAINER_FILE, "")
    body = (
        "Automated PR updating the bazel remote execution containers.\n\n"
        "### Container changes\n\n"
        f"{summarize_container_changes(original_container_file, new_container_file)}\n"
    )

    if pulls.totalCount:
        pull_request = pulls[0]
        pull_request.edit(body=body)
        print(f"Updated existing PR #{pull_request.number}")
    else:
        pull_request = repo.create_pull(
            title=args.pr_title, head=args.new_branch, base=args.base_branch, body=body
        )
        print(f"Created PR #{pull_request.number}")

    print(pull_request.html_url)
    return 0


if __name__ == "__main__":
    sys.exit(main())
