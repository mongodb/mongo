/**
 * Tests polygons whose distinct GeoJSON coordinates collapse into identical S2Points, or whose
 * edges are reported as crossing, because of sin/cos rounding differences across glibc versions
 * Such a polygon is accepted on one platform and rejected on another;
 * geoRecoveryFromSinCosRoundingErrors makes it accepted everywhere.
 *
 * Covers the paths an operator actually hits:
 *   - inserting into a collection that already has a 2dsphere index (key generation on insert),
 *   - building a 2dsphere index over already-stored documents,
 *   - validate(),
 *   - query correctness, including using the degenerate polygon as the query operand, and
 *     cross-checking the index plan against a collection scan.
 *   - index rebuild path: a key generation failure could make the collection lose all the indexes.
 *
 * Whether a given polygon is degenerate depends on the platform's libm, so the test first records
 * which polygons this machine actually rejects with the recovery off, then asserts the recovery rescues
 * exactly those, and that everything else is unchanged. Polygons that are invalid for reasons
 * unrelated to rounding must stay rejected under both settings.
 *
 * @tags: [
 *   requires_persistence,
 * ]
 */
import {isDisagg} from "jstests/libs/oplog_truncation_util.js";
import {
    findPolygonsRejectedWithoutRecovery,
    kAlwaysInvalidPolygons,
    kRecoverablePolygons,
} from "jstests/libs/query/geo_sin_cos_rounding_polygons.js";
import {after, before, describe, it} from "jstests/libs/mochalite.js";

// Raised when key generation rejects the stored geometry.
const kGeoKeyExtractionFailed = ErrorCodes.GeoKeyExtractionFailed;

// Inserts 'geo' into a collection that already has a 2dsphere index, i.e. geo keys are generated as
// part of the insert. Returns the raw write result.
function insertWithIndex(db, geo) {
    const coll = db.index_first;
    coll.drop();
    assert.commandWorked(coll.createIndex({geo: "2dsphere"}));
    return coll.insert({_id: 0, geo: geo});
}

// Inserts 'geo' without an index, then builds one, i.e. geo keys are generated by the index build.
// Returns the createIndexes result.
function indexAfterInsert(db, geo) {
    const coll = db.index_after;
    coll.drop();
    assert.commandWorked(coll.insert({_id: 0, geo: geo}));
    return coll.createIndex({geo: "2dsphere"});
}

// A degenerate polygon must return the same documents whether the query is answered by the
// 2dsphere index or by a collection scan, and it must find the document it was stored as. The
// stored polygon doubles as the query operand.
//
// 'queryOperand', when provided, is a distinct point. For edge-cross corpus entries it sits on
// one of the edges whose crossing RobustCrossingStable suppressed; for such a point the polygon
// is still an invalid loop to the rest of S2, so the only guarantee asserted is that the two
// query paths agree.
function assertQueryPathsAgree(db, name, queryOperand) {
    const coll = db.index_first;

    const stored = coll.findOne({_id: 0}).geo;
    const selfFilter = {geo: {$geoIntersects: {$geometry: stored}}};

    const selfIndexed = coll.find(selfFilter).toArray();
    const selfScanned = coll.find(selfFilter).hint({$natural: 1}).toArray();
    assert.eq(selfIndexed.length, selfScanned.length, `${name}: index and collscan disagree`, {
        selfIndexed,
        selfScanned,
    });
    assert.eq(
        1,
        selfIndexed.length,
        `${name}: polygon does not intersect itself through the index`,
    );

    if (queryOperand) {
        const filter = {geo: {$geoIntersects: {$geometry: queryOperand}}};
        const indexed = coll.find(filter).toArray();
        const scanned = coll.find(filter).hint({$natural: 1}).toArray();
        assert.eq(
            indexed.length,
            scanned.length,
            `${name}: index and collscan disagree on the suppressed-crossing edge`,
            {queryOperand, indexed, scanned},
        );
    }
}

function assertRejected(name, insertRes, when) {
    assert(insertRes.hasWriteError(), `${name}: unexpectedly accepted ${when}`, {insertRes});
    assert.eq(kGeoKeyExtractionFailed, insertRes.getWriteError().code, name, {insertRes});
}

function startMongod(recoveryEnabled) {
    const conn = MongoRunner.runMongod({
        setParameter: {geoRecoveryFromSinCosRoundingErrors: recoveryEnabled},
    });
    assert.neq(null, conn, "mongod failed to start", {recoveryEnabled});
    return conn;
}

// Record which polygons this platform's libm actually makes degenerate, as a module-level value
// computed from a throwaway mongod *before* any describe() block runs.
const probeConn = startMongod(false);
const probeDb = probeConn.getDB(jsTestName());
const rejectedWithoutRecovery = findPolygonsRejectedWithoutRecovery(probeDb);
const runningUnderDisagg = isDisagg(probeConn);
MongoRunner.stopMongod(probeConn);

describe("2dsphere key generation with sin/cos rounding recovery disabled", function () {
    let conn;
    let db;

    before(function () {
        conn = startMongod(false);
        db = conn.getDB(jsTestName());
    });

    after(function () {
        MongoRunner.stopMongod(conn);
    });

    it("treats a rounding-degenerate polygon the same on the insert and index build paths", function () {
        for (const entry of kRecoverablePolygons) {
            const {name, geo} = entry;
            const indexBeforeInsertRes = insertWithIndex(db, geo);
            const indexAfterInsertRes = indexAfterInsert(db, geo);
            if (!indexBeforeInsertRes.hasWriteError() && indexAfterInsertRes.ok) {
                // Not degenerate on this platform; the query paths must still agree.
                assertQueryPathsAgree(db, name, entry.queryOperand);
                continue;
            }
            // indexBeforeInsert and indexAfterInsert should agree
            assert(
                indexBeforeInsertRes.hasWriteError() && !indexAfterInsertRes.ok,
                `${name}: insert and index build disagree`,
                {indexBeforeInsertRes, indexAfterInsertRes},
            );
            assert.eq(kGeoKeyExtractionFailed, indexBeforeInsertRes.getWriteError().code, name);
            assert.commandFailedWithCode(indexAfterInsertRes, kGeoKeyExtractionFailed, name);
            assert(
                rejectedWithoutRecovery.has(name),
                `${name}: not recorded by the platform probe`,
            );
        }
    });

    it("rejects genuinely invalid polygons", function () {
        for (const {name, geo} of kAlwaysInvalidPolygons) {
            assertRejected(name, insertWithIndex(db, geo), "without recovery");
        }
    });
});

describe("2dsphere key generation with sin/cos rounding recovery enabled", function () {
    let conn;
    let db;

    before(function () {
        conn = startMongod(true);
        db = conn.getDB(jsTestName());
    });

    after(function () {
        MongoRunner.stopMongod(conn);
    });

    it("accepts every rounding-degenerate polygon on the insert path", function () {
        for (const {name, geo} of kRecoverablePolygons) {
            assert.commandWorked(insertWithIndex(db, geo), `${name}: rejected on insert`);
        }
    });

    it("accepts every rounding-degenerate polygon on the index build path", function () {
        for (const {name, geo} of kRecoverablePolygons) {
            assert.commandWorked(indexAfterInsert(db, geo), `${name}: rejected on index build`);
        }
    });

    it("validates a collection indexed on a rounding-degenerate polygon", function () {
        for (const {name, geo} of kRecoverablePolygons) {
            assert.commandWorked(insertWithIndex(db, geo));
            const validateRes = assert.commandWorked(db.index_first.validate({full: true}));
            assert(validateRes.valid, `${name}: validate reported an invalid collection`, {
                validateRes,
            });
        }
    });

    it("returns the same results through the index and a collection scan", function () {
        for (const entry of kRecoverablePolygons) {
            const {name, geo} = entry;
            assert.commandWorked(insertWithIndex(db, geo));
            assertQueryPathsAgree(db, name, entry.queryOperand);
        }
    });

    it("rescues every polygon this platform rejected without recovery", function () {
        for (const name of rejectedWithoutRecovery) {
            const {geo} = kRecoverablePolygons.find((p) => p.name === name);
            assert.commandWorked(insertWithIndex(db, geo), `${name}: still rejected with recovery`);
        }
    });

    // Recovery only rescues rounding-induced degeneracy; genuinely invalid geometry stays invalid.
    it("still rejects genuinely invalid polygons", function () {
        for (const {name, geo} of kAlwaysInvalidPolygons) {
            assertRejected(name, insertWithIndex(db, geo), "with recovery");
        }
    });
});

// reIndex over a collection whose polygons are degenerate on one platform but not another.
// reIndex drops every index up front and rebuilds them, so a key generation failure leaves the
// collection with no indexes at all.
// This block is skipped under disaggregated storage: reIndex is standalone-only.
(runningUnderDisagg ? describe.skip : describe)(
    "reIndex over rounding-degenerate polygons",
    function () {
        let conn;
        let dbpath;

        function coll() {
            return conn.getDB(jsTestName()).reindexed;
        }

        function restartWithRecovery(enabled) {
            MongoRunner.stopMongod(conn, undefined, {skipValidation: true});
            conn = MongoRunner.runMongod({
                restart: true,
                cleanData: false,
                dbpath: dbpath,
                setParameter: {geoRecoveryFromSinCosRoundingErrors: enabled},
            });
            assert.neq(null, conn, "mongod failed to restart", {recoveryEnabled: enabled});
        }

        before(function () {
            conn = startMongod(true);
            dbpath = conn.dbpath;
            // Recovery enabled: the polygons insert and the index builds successfully.
            const docs = kRecoverablePolygons.map(({name, geo}, i) => ({
                _id: i,
                name: name,
                geo: geo,
            }));
            assert.commandWorked(coll().insert(docs));
            assert.commandWorked(coll().createIndex({geo: "2dsphere"}, {name: "geo_2dsphere"}));
            assert.eq(2, coll().getIndexes().length);
        });

        after(function () {
            MongoRunner.stopMongod(conn, undefined, {skipValidation: true});
        });

        it("drops every index, including _id_, when reIndex runs without recovery", function () {
            restartWithRecovery(false);
            assert.eq(2, coll().getIndexes().length, "expected the indexes to survive the restart");

            const res = coll().runCommand({reIndex: coll().getName()});
            if (rejectedWithoutRecovery.size === 0) {
                // Nothing in the corpus is degenerate here, so this is an ordinary index rebuild.
                assert.commandWorked(res);
                assert.eq(
                    ["_id_", "geo_2dsphere"],
                    coll()
                        .getIndexes()
                        .map((ix) => ix.name)
                        .sort(),
                );
                return;
            }
            assert.commandFailedWithCode(res, ErrorCodes.GeoKeyExtractionFailed);
            // The damage: reIndex dropped the indexes before rebuilding them, and the failed rebuild
            // leaves none behind.
            assert.eq(
                [],
                coll().getIndexes(),
                "expected reIndex to leave the collection unindexed",
            );
            // The documents themselves are untouched.
            assert.eq(kRecoverablePolygons.length, coll().find().itcount());
        });

        it("rebuilds every index when reIndex runs with recovery", function () {
            restartWithRecovery(true);
            // Recreate the index the case above may have destroyed. Harmless when it survived.
            assert.commandWorked(coll().createIndex({geo: "2dsphere"}, {name: "geo_2dsphere"}));

            assert.commandWorked(coll().runCommand({reIndex: coll().getName()}));
            assert.eq(
                ["_id_", "geo_2dsphere"],
                coll()
                    .getIndexes()
                    .map((ix) => ix.name)
                    .sort(),
            );
            const validateRes = assert.commandWorked(coll().validate({full: true}));
            assert(validateRes.valid, "expected a valid collection after reIndex", {validateRes});
            assert.gt(validateRes.keysPerIndex["geo_2dsphere"], 0, "expected geo keys", {
                validateRes,
            });
        });
    },
);
