#include "mongo/bson/bsonobj.h"
#include "mongo/bson/bsonobjbuilder.h"

#include <cstddef>
#include <cstdint>
#include <limits>
#include <string>
#include <string_view>
#include <type_traits>
#include <variant>
#include <vector>

#include <absl/strings/str_format.h>
#include <fuzztest/fuzztest.h>

namespace mongo::sbe {

/**
 * Fuzzer domain for generating arbitrary documents as inputs for SBE stages.
 * FuzzTest domains don't support nesting, so the fuzzer generates a flat vector of NodeSpecs which
 * is rendered into a nested document. Each node in the spec is an object, scalar, or Nothing.
 * The document is assembled by traversing the nodes, and for every object node with n children,
 * the next n nodes are appended into that object at sequential field names. "Nothing" represents a
 * missing field in an object, so the next field name is skipped and the children are appended
 * starting from the next node. In an array, Nothing is skipped over. The tree is limited to a
 * branching factor (max number of children for a node) and max tree depth. Every fuzzer input
 * results in a valid tree: all nodes in the spec are consumed, and if the spec runs out of nodes
 * before all object/array children are populated those nodes are skipped.
 */

// max depth from the root document
inline constexpr unsigned kMaxTreeDepth = 5;
// max branching factor, enforced on nodes below the root
inline constexpr unsigned kMaxTreeBranching = 8;
// max number of generated nodes per document
inline constexpr unsigned kMaxDocumentNodes = 128;

struct NullSpec {
    bool operator==(const NullSpec&) const = default;
};

struct NothingSpec {
    bool operator==(const NothingSpec&) const = default;
};

using ScalarSpec = std::variant<bool, int32_t, int64_t, double, std::string, NullSpec, NothingSpec>;

struct ObjectSpec {
    unsigned childCount = 0;
    bool operator==(const ObjectSpec&) const = default;
};

struct ArraySpec {
    unsigned childCount = 0;
    bool operator==(const ArraySpec&) const = default;
};

using NodeSpec = std::variant<ScalarSpec, ObjectSpec, ArraySpec>;

// The input from the fuzzer - a flat vector of nodes that is rendered into a nested document tree
using DocumentSpec = std::vector<NodeSpec>;

/**
 * Renders the spec generated by the fuzzer into a nested document {"_id": id, ...}
 * The root node is an object whose children are assembled from the spec in preorder, with scalars
 * stored as leaf nodes and container nodes storing the next childCount assembled nodes as their
 * children.
 */
BSONObj renderDocument(const DocumentSpec& spec, long long id);

/**
 * Renders the spec into the fields of its nested document, without the "_id" field.
 */
BSONObj renderDocumentFields(const DocumentSpec& spec);

// These functions are here so that ADL works properly in order to print the fuzzer-generated
// documents as JSON whenever the fuzzer finds a failure.
template <typename Sink>
void AbslStringify(Sink& sink, const DocumentSpec& spec) {
    absl::Format(&sink, "%s", renderDocumentFields(spec).jsonString());
}

/**
 * Field name for a value in an object based on position and the depth of the object. At document
 * level 0 the field names are a0, a1..., at level 1 b0, b1..., etc
 */
inline std::string positionalName(unsigned idx, unsigned depth = 0) {
    return std::string(1, static_cast<char>('a' + depth)) + std::to_string(idx);
}

inline auto int32Domain() {
    return fuzztest::OneOf(fuzztest::InRange<int32_t>(-1, 1),
                           fuzztest::InRange<int32_t>(-3, 3),
                           fuzztest::InRange<int32_t>(-20, 20),
                           fuzztest::Arbitrary<int32_t>(),
                           fuzztest::ElementOf<int32_t>({std::numeric_limits<int32_t>::min(),
                                                         std::numeric_limits<int32_t>::max()}));
}

inline auto int64Domain() {
    return fuzztest::OneOf(fuzztest::InRange<int64_t>(-1, 1),
                           fuzztest::InRange<int64_t>(-3, 3),
                           fuzztest::InRange<int64_t>(-20, 20),
                           fuzztest::Arbitrary<int64_t>(),
                           fuzztest::ElementOf<int64_t>({std::numeric_limits<int64_t>::min(),
                                                         std::numeric_limits<int64_t>::max()}));
}

// Group keys repeat across documents only when field values repeat, so the scalar domains layer
// small ranges (which collide often) with arbitrary and extreme values (which cover the type).
inline auto doubleDomain() {
    return fuzztest::OneOf(fuzztest::InRange<double>(-2.0, 2.0), fuzztest::Arbitrary<double>());
}

inline auto stringDomain() {
    return fuzztest::OneOf(fuzztest::ElementOf<std::string>({"", "a", "b", "abc", "a0"}),
                           fuzztest::Arbitrary<std::string>().WithMaxSize(16));
}

inline auto scalarSpecDomain() {
    return fuzztest::VariantOf(fuzztest::Arbitrary<bool>(),
                               int32Domain(),
                               int64Domain(),
                               doubleDomain(),
                               stringDomain(),
                               fuzztest::Just(NullSpec{}),
                               fuzztest::Just(NothingSpec{}));
}

inline auto objectSpecDomain() {
    return fuzztest::StructOf<ObjectSpec>(fuzztest::InRange<unsigned>(0, kMaxTreeBranching)
                                              .WithSeeds(std::vector<unsigned>{kMaxTreeBranching}));
}

inline auto arraySpecDomain() {
    return fuzztest::StructOf<ArraySpec>(fuzztest::InRange<unsigned>(0, kMaxTreeBranching)
                                             .WithSeeds(std::vector<unsigned>{kMaxTreeBranching}));
}

inline auto nodeSpecDomain() {
    return fuzztest::VariantOf(scalarSpecDomain(), objectSpecDomain(), arraySpecDomain());
}

/**
 * Input domain for a single document (vector of Nodes from which a tree is assembled). The identity
 * Map wrapper routes printing through the AbslStringify overload.
 */
inline auto documentNodesDomain() {
    return fuzztest::Map(
        [](DocumentSpec spec) { return spec; },
        // each option has equal probability and fuzztest starts with the smallest size for each
        fuzztest::OneOf(fuzztest::VectorOf(nodeSpecDomain()).WithMinSize(2),
                        fuzztest::VectorOf(nodeSpecDomain()).WithMinSize(64),
                        fuzztest::VectorOf(nodeSpecDomain()).WithMinSize(128)));
}

}  // namespace mongo::sbe
