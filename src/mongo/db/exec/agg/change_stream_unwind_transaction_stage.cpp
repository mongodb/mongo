ChangeStreamUnwindTransactionStage::ChangeStreamUnwindTransactionStage(
    std::string_view stageName,
    const boost::intrusive_ptr<ExpressionContext>& pExpCtx,
    BSONObj filter,
    std::shared_ptr<MatchExpression> expression)
    : Stage(stageName, pExpCtx),
      _endOfTransactionOptions({change_stream::determineEndOfTransactionBehavior(pExpCtx),
                                resolveEndOfTransactionMode(pExpCtx),
                                pExpCtx->getFromRouter()}),
      _changeStream(ChangeStream::buildFromExpressionContext(pExpCtx)),
      _filter(std::move(filter)),
      _expression(std::move(expression)) {
    tassert(5543812,
            str::stream() << DocumentSourceChangeStreamUnwindTransaction::kStageName
                          << " cannot be executed from router",
            !pExpCtx->getInRouter());

    if (_endOfTransactionOptions.mode == EndOfTransactionMode::kRequired) {
        // Record on the operation so it rides onto the ClientCursor; the getMore precondition uses
        // it to fail the cursor if the feature flag or the 'allowEndOfTransaction' server parameter
        // is turned off after the stream was opened.
        CurOp::get(pExpCtx->getOperationContext())->debug().requiresEndOfTransaction = true;
    }

    // This filter is applied to every individual operation unwound from an 'applyOps' entry, so a
    // single large transaction can evaluate it many times. The expression belongs to this execution
    // stage and is not serialized back out, so it is safe to reorder.
    allowReordering(pExpCtx->getOperationContext(), _expression.get());
}

bool ChangeStreamUnwindTransactionStage::_endOfTransactionScopesCoverWatchedScope(
    const Document& scopes) const {
    // A record only carries information for the router if it comes from a write participant of the
    // watched scope: the router completes a transaction once every participant of the watched scope
    // has been seen, so a record from a shard that wrote only other collections is dropped there.
    // Report only when this shard is one of the watched scope's participants, so such records are
    // not sent to the router at all.
    const Value shardId = scopes["shardId"sv];
    if (shardId.getType() != BSONType::string) {
        return false;
    }
    const std::string_view reportingShard = shardId.getStringData();
    const boost::optional<NamespaceString> watchedNamespace = _changeStream.getNamespace();
    switch (_changeStream.getChangeStreamType()) {
        case ChangeStreamType::kCollection: {
            const std::string key = str::stream()
                << watchedNamespace->dbName().db(omitTenant) << "." << watchedNamespace->coll();
            return participantMapContainsShard(
                scopes["collectionParticipants"sv], key, reportingShard);
        }
        case ChangeStreamType::kDatabase: {
            const std::string key{watchedNamespace->dbName().db(omitTenant)};
            return participantMapContainsShard(
                scopes["databaseParticipants"sv], key, reportingShard);
        }
        case ChangeStreamType::kAllDatabases:
            // Every write participant is a cluster participant, so the reporting shard always
            // covers a whole-cluster stream.
            return true;
    }
    MONGO_UNREACHABLE_TASSERT(13875100);
}

GetNextResult ChangeStreamUnwindTransactionStage::doGetNext() {
    while (true) {
        // If we're unwinding an 'applyOps' from a transaction, check if there are any documents
        // we have stored that can be returned.
        if (_txnIterator) {
            if (auto next = _txnIterator->getNextTransactionOp(pExpCtx->getOperationContext())) {
                // A coordinated transaction's accounting control event is marked as a change
                // stream control event and must be returned with the control-document status so
                // that the intervening stages pass it through unchanged and the router can consume
                // it. Every other result is a regular, user-visible event.
                if (next->metadata().isChangeStreamControlEvent()) {
                    tassert(13875105,
                            "expecting accounting control event",
                            next->metadata().getChangeStreamControlEventType() ==
                                DocumentMetadataFields::ChangeStreamControlEventType::kAccounting);
                    return GetNextResult::makeAdvancedControlDocument(std::move(*next));
                }
                return std::move(*next);
            }

            _txnIterator = boost::none;
        }

        // Get the next input document.
        auto input = pSource->getNext();
        if (!input.isAdvanced()) {
            return input;
        }

        auto doc = input.releaseDocument();

        // If the oplog entry is not part of a transaction, allow it to pass through.
        if (!_isTransactionOplogEntry(doc)) {
            return doc;
        }

        // The only two commands we will see here are an applyOps or a commit, which both mean
        // we need to open a "transaction context" representing a group of updates that all
        // occurred at once as part of a transaction. If we already have a transaction context
        // open, that would mean we are looking at an applyOps or commit nested within an
        // applyOps, which is not allowed in the oplog.
        tassert(5543801, "Transaction iterator found, but expected none", !_txnIterator);

        // Once we initialize the transaction iterator, we can loop back to the top in order to
        // call 'getNextTransactionOp' on it. Note that is possible for the transaction iterator
        // to be empty of any relevant operations, meaning that this loop may need to execute
        // multiple times before it encounters a relevant change to return.
        _txnIterator.emplace(this, pExpCtx, doc, _expression.get(), _endOfTransactionOptions);
    }
}

bool ChangeStreamUnwindTransactionStage::_isTransactionOplogEntry(const Document& doc) {
    auto op = doc[FieldAccessors::kOpType];
    auto opType = idl::deserialize<repl::OpTypeEnum>(op.getStringData(),
                                                     IDLParserContext("ChangeStreamEntry.op"));

    if (opType != repl::OpTypeEnum::kCommand) {
        // Hot path.
        return false;
    }

    // Cold path.
    auto commandVal = doc[FieldAccessors::kObject];
    if (commandVal["applyOps"sv].missing() && commandVal["commitTransaction"sv].missing()) {
        // We should never see an "abortTransaction" command at this point.
        tassert(5543802,
                str::stream() << "Unexpected op at "
                              << doc[FieldAccessors::kTimestamp].getTimestamp().toString(),
                commandVal["abortTransaction"sv].missing());
        return false;
    }

    return true;
}

ChangeStreamUnwindTransactionStage::TransactionOpIterator::TransactionOpIterator(
    const ChangeStreamUnwindTransactionStage* stage,
    const boost::intrusive_ptr<ExpressionContext>& expCtx,
    const Document& input,
    const MatchExpression* expression,
    EndOfTransactionOptions endOfTransactionOptions)
    : _mongoProcessInterface(expCtx->getMongoProcessInterface()),
      _expression(expression),
      _endOfTransactionExpression(change_stream_filter::buildEndOfTransactionFilter(
          expCtx, endOfTransactionOptions.behavior, endOfTransactionOptions.mode)),
      _changeStreamTokenVersion(expCtx->getChangeStreamTokenVersion()),
      _endOfTransactionBehavior(endOfTransactionOptions.behavior) {

    Value multiOpTypeValue = input[repl::OplogEntry::kMultiOpTypeFieldName];
    DocumentSourceChangeStream::checkValueTypeOrMissing(
        multiOpTypeValue, repl::OplogEntry::kMultiOpTypeFieldName, BSONType::numberInt);
    const boost::optional<repl::MultiOplogEntryType> multiOpType = multiOpTypeValue.missing()
        ? boost::none
        : boost::make_optional(static_cast<repl::MultiOplogEntryType>(multiOpTypeValue.getInt()));
    const bool applyOpsAppliedSeparately =
        multiOpType == repl::MultiOplogEntryType::kApplyOpsAppliedSeparately;
    const bool isRetryableApplyOps = applyOpsAppliedSeparately ||
        multiOpType == repl::MultiOplogEntryType::kApplyOpsAppliedAtomically;

    // lsid and txnNumber identify the transaction an operation belongs to and are surfaced on its
    // change event so clients can correlate events from the same transaction. They are not parsed
    // for retryable-write applyOps, which are not transactions.
    if (!isRetryableApplyOps) {
        Value lsidValue = input[DocumentSourceChangeStream::kLsidField];
        DocumentSourceChangeStream::checkValueTypeOrMissing(
            lsidValue, DocumentSourceChangeStream::kLsidField, BSONType::object);
        _lsid =
            lsidValue.missing() ? boost::none : boost::optional<Document>(lsidValue.getDocument());
        Value txnNumberValue = input[DocumentSourceChangeStream::kTxnNumberField];
        DocumentSourceChangeStream::checkValueTypeOrMissing(
            txnNumberValue, DocumentSourceChangeStream::kTxnNumberField, BSONType::numberLong);
        _txnNumber = txnNumberValue.missing()
            ? boost::none
            : boost::optional<TxnNumber>(txnNumberValue.getLong());
    }
    // We want to parse the OpTime out of this document using the BSON OpTime parser. Instead of
    // converting the entire Document back to BSON, we convert only the fields we need.
    repl::OpTime txnOpTime = repl::OpTime::parse(BSON(repl::OpTime::kTimestampFieldName
                                                      << input[repl::OpTime::kTimestampFieldName]
                                                      << repl::OpTime::kTermFieldName
                                                      << input[repl::OpTime::kTermFieldName]));
    _clusterTime = txnOpTime.getTimestamp();

    Value wallTime = input[FieldAccessors::kWallClockTime];
    DocumentSourceChangeStream::checkValueType(
        wallTime, repl::OplogEntry::kWallClockTimeFieldName, BSONType::date);
    _wallTime = wallTime.getDate();

    auto commandObj = input[FieldAccessors::kObject].getDocument();
    Value applyOps = commandObj["applyOps"sv];
    const bool isApplyOpsEntry = !applyOps.missing();
    const bool isCommitTransactionEntry = !commandObj["commitTransaction"sv].missing();

    if (isApplyOpsEntry) {
        // We found an applyOps that implicitly commits a transaction. We include it in the
        // '_txnOplogEntries' stack of applyOps entries that the change stream should process as
        // part of this transaction. There may be additional applyOps entries linked through the
        // 'prevOpTime' field, which will also get added to '_txnOplogEntries' later in this
        // function. Note that this style of transaction does not have a 'commitTransaction'
        // command.
        _txnOplogEntries.push(txnOpTime);
    } else {
        // This must be a "commitTransaction" command, which commits a prepared transaction.
        // This style of transaction does not have an applyOps entry that implicitly commits it,
        // as in the previous case. We're going to iterate through the other oplog entries in
        // the transaction, but this entry does not have any updates in it, so we do not include
        // it in the '_txnOplogEntries' stack.
        tassert(5543803,
                str::stream() << "Unexpected op at "
                              << input[FieldAccessors::kTimestamp].getTimestamp().toString(),
                isCommitTransactionEntry);

        if (auto commitTimestamp = commandObj["commitTimestamp"]; !commitTimestamp.missing()) {
            // Track commit timestamp of the prepared transaction if it's present in the oplog
            // entry.
            _commitTimestamp = commitTimestamp.getTimestamp();
        }
    }

    // An endOfTransaction event is synthesized for a committed multi-document transaction that
    // carries an 'lsid' and 'txnNumber' and is not a retryable-write applyOps. Such a transaction
    // commits through one of the following oplog shapes. Only the commit entry opens the
    // transaction context here: the oplog match filters out the prepare entry, and the iterator
    // then walks 'prevOpTime' to collect the transaction's operations.
    //
    //  - Unprepared (replica set, or a single shard committed by the router): the operations are
    //    one or more 'applyOps' entries chained through 'prevOpTime', and the final entry
    //    implicitly commits the transaction. Each entry carries 'lsid', 'txnNumber' and
    //    'o.applyOps'; the final entry additionally carries 'o.allowEndOfTransaction: true' when
    //    the write path was enabled at commit time. There is no 'commitTransaction' entry.
    //  - Prepared (replica set, or a single shard committed locally): the operations are written
    //    by a prepare entry, an 'applyOps' entry carrying 'o.prepare: true'. The commit is a
    //    standalone 'commitTransaction' entry carrying 'lsid', 'txnNumber', 'prevOpTime' pointing
    //    at the prepare entry, 'o.commitTransaction: 1', 'o.commitTimestamp', and
    //    'o2.allowEndOfTransaction: true' when the write path was enabled at commit time.
    //  - Coordinated (multi-shard) participant commit: a write participant shard writes a
    //    'commitTransaction' entry of the prepared shape, plus the coordinator's
    //    'o.endOfTransactionScopes' accounting metadata. Its user-visible event is produced by the
    //    router from the coordinator's accounting control event, a no-op ('n') entry carrying
    //    'o2.endOfTransaction', so this stage must neither synthesize an event for it nor treat it
    //    as ineligible.
    //
    // The behavior was resolved once when the stage was created:
    //  - 'kLegacy' synthesizes the event for every unprepared transaction, and
    //  - 'kNew' additionally requires the 'allowEndOfTransaction' marker, which records that the
    //    write path was enabled when the transaction committed, so a transaction committed while
    //    the kill switch was off never yields an event.
    // TODO SERVER-138462 Remove feature flag for legacy endOfTransaction behavior.
    Value o2 = input[FieldAccessors::kObject2];
    const bool hasAllowEndOfTransaction =
        (isApplyOpsEntry && commandObj["allowEndOfTransaction"sv].coerceToBool()) ||
        (isCommitTransactionEntry && !o2.missing() &&
         o2.getDocument()["allowEndOfTransaction"sv].coerceToBool());
    const bool hasEndOfTransactionScopes =
        isCommitTransactionEntry && !commandObj["endOfTransactionScopes"sv].missing();

    // Check if the behavior allows emitting an "endOfTransaction" change event from this stage:
    // For the legacy mode, only "applyOps" entries qualify. Commit events for coordinated
    // transactions are ignored in legacy mode, because the legacy mode writes a separate
    // "endOfTransaction" oplog entry on the coordinator, which is emitted directly and not from
    // here. In the new mode, we only emit an "endOfTransaction" change event from here for the
    // final entry in an "applyOps" oplog entry. The path for emitting an "endOfTransaction" control
    // event from a "commitTransaction" oplog entry is not added here yet.
    const bool behaviorAllowsEmit =
        _endOfTransactionBehavior == change_stream::EndOfTransactionBehavior::kLegacy
        ? isApplyOpsEntry
        : (_endOfTransactionBehavior == change_stream::EndOfTransactionBehavior::kNew &&
           hasAllowEndOfTransaction);

    // Check if the oplog entry is a candidate for emitting an "endOfTransaction" change event from
    // this stage.
    const bool endOfTransactionCandidate = (isApplyOpsEntry || isCommitTransactionEntry) &&
        !isRetryableApplyOps && _lsid.has_value() && _txnNumber.has_value();
    // Resolve what to do with this transaction once all of its operations have been consumed. A
    // coordinated (multi-shard) transaction's commit entry carries the 'endOfTransactionScopes'
    // accounting metadata; its event is produced from that metadata rather than synthesized from
    // the entry's operations, so those cases are resolved first. Otherwise, a 'required' stream
    // that reads an ineligible transaction must fail, and only then does a regular synthesized
    // event remain possible.
    if (hasEndOfTransactionScopes) {
        // Only the synthesis behavior ('kNew') turns a coordinated commit entry into an event: the
        // legacy behavior emits from the separate 'o2.endOfTransaction' entry, and the kill switch
        // (or a disabled feature flag) resolves to 'kNone'. Gating on the behavior, not just the
        // opt-in mode, is required for the kill switch to take effect: when no event can be
        // synthesized the namespace predicate below is not applied, so emitting anyway would leak
        // an unrelated transaction's session id, transaction number, commit timestamp and affected
        // namespaces into the stream.
        //
        // A router-bound stream delivers the metadata to the router as an accounting control event,
        // and only when the metadata references the watched scope. A passthrough / direct-to-mongod
        // stream runs entirely on the shard and has no router to consume control events, so it
        // emits the user-visible endOfTransaction event directly; whether the transaction touches
        // the watched scope is decided later, by the same namespace-based predicate used for the
        // unprepared path.
        if (_endOfTransactionBehavior == change_stream::EndOfTransactionBehavior::kNew) {
            if (endOfTransactionOptions.fromRouter) {
                Document scopes = commandObj["endOfTransactionScopes"sv].getDocument();
                if (stage->_endOfTransactionScopesCoverWatchedScope(scopes)) {
                    _endOfTransactionAction = EndOfTransactionAction::kEmitAccountingControlEvent;
                    _endOfTransactionScopes = std::move(scopes);
                }
            } else {
                _endOfTransactionAction = EndOfTransactionAction::kEmitCoordinatedUserVisible;
            }
        }
    } else if (endOfTransactionOptions.mode == EndOfTransactionMode::kRequired &&
               endOfTransactionCandidate && !hasAllowEndOfTransaction) {
        // A 'required' stream must fail rather than silently omit an endOfTransaction event. An
        // event can only be synthesized for a transaction that carries the 'allowEndOfTransaction'
        // marker, which is written at commit time only while the write path was enabled. Without
        // the marker the transaction is ineligible and no event can ever be produced, so the
        // guarantee cannot be met: record that here so the iterator fails the stream if the
        // transaction touches the watched namespace. When the marker is present the event is
        // emitted normally via 'kEmitUserVisible' and no failure is needed. A transaction that
        // carries 'endOfTransactionScopes' is not ineligible: its event is produced from the
        // accounting metadata by the router, so it must never fail a 'required' stream.
        _endOfTransactionAction = EndOfTransactionAction::kFailIfIneligibleTouchesWatchedNamespace;
    } else if (endOfTransactionCandidate && behaviorAllowsEmit) {
        // The transaction is an eligible candidate and the resolved behavior allows emitting a
        // synthesized event for it.
        _endOfTransactionAction = EndOfTransactionAction::kEmitUserVisible;
    }

    // When operations span multiple applyOps entries linked by 'prevOpTime', walk that chain to
    // gather them all. kApplyOpsAppliedSeparately entries are standalone, so there is no chain to
    // follow. kApplyOpsAppliedAtomically entries also use 'prevOpTime' to link between retryable
    // write statements, so bound its walk by the terminal's 'count' of operations. A terminal
    // entry without 'count' is a single-entry batch with no chain to walk. See walkApplyOpsChain().
    boost::optional<std::size_t> opsStillToCollect;
    if (isRetryableApplyOps) {
        const Value count = commandObj["count"sv];
        opsStillToCollect = count.missing()
            ? 0
            : repl::remainingApplyOpsChainOps(static_cast<std::size_t>(count.getLong()),
                                              repl::numOperationsInApplyOps(applyOps));
    }

    if (!applyOpsAppliedSeparately &&
        BSONType::object ==
            input[repl::OplogEntry::kPrevWriteOpTimeInTransactionFieldName].getType()) {
        // As with the 'txnOpTime' parsing above, we convert a portion of 'input' back to BSON
        // in order to parse an OpTime, this time from the "prevOpTime" field.
        repl::OpTime prevOpTime = repl::OpTime::parse(
            input[repl::OplogEntry::kPrevWriteOpTimeInTransactionFieldName].getDocument().toBson());
        _collectAllOpTimesFromTransaction(
            expCtx->getOperationContext(), prevOpTime, opsStillToCollect);
    }

    // Pop the first OpTime off the stack and use it to load the first oplog entry into the
    // '_currentApplyOps' field.
    tassert(5543804, "No transaction oplog entries found", _txnOplogEntries.size() > 0);
    const auto firstTimestamp = _txnOplogEntries.top();
    _txnOplogEntries.pop();

    if (firstTimestamp == txnOpTime) {
        // This transaction consists of only one oplog entry, from which we have already
        // extracted the "applyOps" array, so there is no need to do any more work.
        tassert(5543805,
                str::stream() << "Expected no transaction entries, found "
                              << _txnOplogEntries.size(),
                _txnOplogEntries.size() == 0);
        _currentApplyOps = std::move(applyOps);
    } else {
        // This transaction consists of multiple oplog entries; grab the chronologically first
        // entry and extract its "applyOps" array.
        auto firstApplyOpsEntry =
            _lookUpOplogEntryByOpTime(expCtx->getOperationContext(), firstTimestamp);

        auto bsonOp = firstApplyOpsEntry.getOperationToApply();
        tassert(5543806,
                str::stream() << "Expected 'applyOps' type " << BSONType::array << ", found "
                              << bsonOp["applyOps"].type(),
                BSONType::array == bsonOp["applyOps"].type());
        _currentApplyOps = Value(bsonOp["applyOps"]);
    }

    DocumentSourceChangeStream::checkValueType(_currentApplyOps, "applyOps", BSONType::array);

    // Initialize iterators at the beginning of the transaction.
    _currentApplyOpsIt = _currentApplyOps.getArray().begin();
    _currentApplyOpsTs = firstTimestamp.getTimestamp();
    _currentApplyOpsIndex = 0;
    _txnOpIndex = 0;
}

boost::optional<Document>
ChangeStreamUnwindTransactionStage::TransactionOpIterator::getNextTransactionOp(
    OperationContext* opCtx) {
    while (true) {
        while (_currentApplyOpsIt != _currentApplyOps.getArray().end()) {
            Document doc = (_currentApplyOpsIt++)->getDocument();
            ++_currentApplyOpsIndex;
            ++_txnOpIndex;

            _assertExpectedTransactionEventFormat(doc);

            if (_needsAffectedNamespaces(_endOfTransactionAction)) {
                _addAffectedNamespaces(doc);
            }
            // If the document is relevant, update it with the required txn fields before returning.
            if (exec::matcher::matchesBSON(_expression, doc.toBson())) {
                return _addRequiredTransactionFields(doc);
            }
        }

        if (_txnOplogEntries.empty()) {
            // There are no more operations in this transaction.
            return _createEndOfTransactionIfNeeded();
        }

        // We've processed all the operations in the previous applyOps entry, but we have a new
        // one to process.
        auto applyOpsEntry = _lookUpOplogEntryByOpTime(opCtx, _txnOplogEntries.top());
        _txnOplogEntries.pop();

        auto bsonOp = applyOpsEntry.getOperationToApply();
        tassert(5543807,
                str::stream() << "Expected 'applyOps' type " << BSONType::array << ", found "
                              << bsonOp["applyOps"].type(),
                BSONType::array == bsonOp["applyOps"].type());

        _currentApplyOps = Value(bsonOp["applyOps"]);
        _currentApplyOpsTs = applyOpsEntry.getTimestamp();
        _currentApplyOpsIt = _currentApplyOps.getArray().begin();
        _currentApplyOpsIndex = 0;
    }
}

void ChangeStreamUnwindTransactionStage::TransactionOpIterator::
    _assertExpectedTransactionEventFormat(const Document& doc) const {
    Value op = doc[FieldAccessors::kOpType];
    tassert(5543808,
            str::stream() << "Unexpected format for entry within a transaction oplog entry: "
                             "'op' field was type "
                          << typeName(op.getType()),
            op.getType() == BSONType::string);
    tassert(5543809,
            str::stream() << "Unexpected noop entry within a transaction " << redact(op.toString()),
            op.getStringData() != "n"sv);
}

Document ChangeStreamUnwindTransactionStage::TransactionOpIterator::_addRequiredTransactionFields(
    const Document& doc) const {
    MutableDocument newDoc(doc);
    // The 'getNextTransactionOp' increments the '_txnOpIndex' by 1, to point to the next
    // transaction number. The 'txnOpIndex()' must be called to get the current transaction number.
    newDoc.addField(DocumentSourceChangeStream::kTxnOpIndexField,
                    Value(static_cast<long long>(txnOpIndex())));

    // The 'getNextTransactionOp' updates the '_currentApplyOpsIndex' to point to the next entry in
    // the '_currentApplyOps' array. The 'applyOpsIndex()' method must be called to get the index of
    // the current entry.
    newDoc.addField(DocumentSourceChangeStream::kApplyOpsIndexField,
                    Value(static_cast<long long>(applyOpsIndex())));
    newDoc.addField(DocumentSourceChangeStream::kApplyOpsTsField, Value(applyOpsTs()));

    newDoc.addField(repl::OplogEntry::kTimestampFieldName, Value(_clusterTime));
    newDoc.addField(repl::OplogEntry::kWallClockTimeFieldName, Value(_wallTime));

    newDoc.addField(DocumentSourceChangeStream::kCommitTimestampField,
                    _commitTimestamp ? Value(*_commitTimestamp) : Value());

    newDoc.addField(repl::OplogEntry::kSessionIdFieldName, _lsid ? Value(*_lsid) : Value());
    newDoc.addField(repl::OplogEntry::kTxnNumberFieldName,
                    _txnNumber ? Value(static_cast<long long>(*_txnNumber)) : Value());

    return newDoc.freeze();
}

repl::OplogEntry
ChangeStreamUnwindTransactionStage::TransactionOpIterator::_lookUpOplogEntryByOpTime(
    OperationContext* opCtx, repl::OpTime lookupTime) const {
    tassert(5543811, "Cannot look up transaction entry with null op time", !lookupTime.isNull());

    std::unique_ptr<TransactionHistoryIteratorBase> iterator(
        _mongoProcessInterface->createTransactionHistoryIterator(lookupTime));

    try {
        return iterator->next(opCtx);
    } catch (ExceptionFor<ErrorCodes::IncompleteTransactionHistory>& ex) {
        ex.addContext(
            str::stream()
            << "Oplog no longer has history necessary for $changeStream to observe operations "
               "from a committed transaction (lookupTime: "
            << lookupTime.getTimestamp() << ")");
        uasserted(ErrorCodes::ChangeStreamHistoryLost, ex.reason());
    }
}

void ChangeStreamUnwindTransactionStage::TransactionOpIterator::_collectAllOpTimesFromTransaction(
    OperationContext* opCtx,
    repl::OpTime firstOpTime,
    boost::optional<std::size_t> opsStillToCollect) {
    // A single-entry batch links to the previous applyOps chain with nothing of its own to walk.
    if (opsStillToCollect && *opsStillToCollect == 0) {
        return;
    }

    std::unique_ptr<TransactionHistoryIteratorBase> iterator(
        _mongoProcessInterface->createTransactionHistoryIterator(firstOpTime));

    try {
        walkApplyOpsChain(*iterator, opsStillToCollect, [&]() -> std::size_t {
            if (!opsStillToCollect) {
                // A transaction walks the whole chain and only needs each entry's optime; the
                // returned op count is unused when there is no budget to decrement.
                _txnOplogEntries.push(iterator->nextOpTime(opCtx));
                return 0;
            }
            // A retryable chain is bounded by 'count', so fetch the entry to count its operations.
            const auto entry = iterator->next(opCtx);
            _txnOplogEntries.push(entry.getOpTime());
            return repl::numOperationsInApplyOps(entry);
        });
    } catch (ExceptionFor<ErrorCodes::IncompleteTransactionHistory>& ex) {
        ex.addContext(
            str::stream()
            << "Oplog no longer has history necessary for $changeStream to observe operations "
               "from a committed transaction (firstOpTime: "
            << firstOpTime.getTimestamp() << ")");
        uasserted(ErrorCodes::ChangeStreamHistoryLost, ex.reason());
    }
}

bool ChangeStreamUnwindTransactionStage::TransactionOpIterator::_needsAffectedNamespaces(
    EndOfTransactionAction action) {
    switch (action) {
        case EndOfTransactionAction::kEmitUserVisible:
        case EndOfTransactionAction::kEmitCoordinatedUserVisible:
        case EndOfTransactionAction::kFailIfIneligibleTouchesWatchedNamespace:
            // These actions build the synthesized event and evaluate it against the namespace-based
            // predicate, so the transaction's affected namespaces must be tracked.
            return true;
        case EndOfTransactionAction::kEmitAccountingControlEvent:
        case EndOfTransactionAction::kNone:
            // The accounting control event is built from the commit entry's
            // 'endOfTransactionScopes' metadata, and the no-op case needs no event at all.
            return false;
    }
    MONGO_UNREACHABLE_TASSERT(13875104);
}

void ChangeStreamUnwindTransactionStage::TransactionOpIterator::_addAffectedNamespaces(
    const Document& doc) {
    const auto dbCmdNs = NamespaceStringUtil::deserialize(/*tenantId=*/boost::none,
                                                          doc["ns"sv].getStringData(),
                                                          SerializationContext::stateDefault());
    if (doc[FieldAccessors::kOpType].getStringData() != "c"sv) {
        _affectedNamespaces.insert(dbCmdNs);
        return;
    }

    // The only supported DDL commands inside transactions are "create" and "createIndexes".
    // Creating databases, dropping collections, databases or indexes are not supported. Neither are
    // renaming nor collMod operations.
    constexpr std::array<std::string_view, 2> kCollectionField = {"create"sv, "createIndexes"sv};
    const Document& object = doc[FieldAccessors::kObject].getDocument();
    for (const auto& fieldName : kCollectionField) {
        const auto field = object[fieldName];
        if (field.getType() == BSONType::string) {
            _affectedNamespaces.insert(
                NamespaceStringUtil::deserialize(dbCmdNs.dbName(), field.getStringData()));
            return;
        }
    }

    tasserted(7694300,
              str::stream() << "Unexpected op in applyOps at " << _currentApplyOpsTs << " index "
                            << _currentApplyOpsIndex << " object " << redact(object.toString()));
}

Document
ChangeStreamUnwindTransactionStage::TransactionOpIterator::_makeEndOfTransactionDocument() {
    ++_currentApplyOpsIndex;
    ++_txnOpIndex;

    std::vector<NamespaceString> namespaces{_affectedNamespaces.begin(), _affectedNamespaces.end()};
    auto lsid = LogicalSessionId::parse(_lsid->toBson(), IDLParserContext("LogicalSessionId"));
    repl::MutableOplogEntry oplogEntry = change_stream::createEndOfTransactionOplogEntry(
        lsid, *_txnNumber, namespaces, _clusterTime, _wallTime);

    // The 'kNew' behavior uses the reserved 'kEndOfTransactionTxnOpIndex' so that its token sorts
    // after every operation of the transaction; the legacy behavior keeps the index after the last
    // operation, preserving its existing tokens.
    const size_t endOfTransactionTxnOpIndex =
        _endOfTransactionBehavior == change_stream::EndOfTransactionBehavior::kNew
        ? kEndOfTransactionTxnOpIndex
        : txnOpIndex();

    MutableDocument newDoc(Document(oplogEntry.toBSON()));
    newDoc.addField(DocumentSourceChangeStream::kTxnOpIndexField,
                    Value(static_cast<long long>(endOfTransactionTxnOpIndex)));
    newDoc.addField(DocumentSourceChangeStream::kApplyOpsIndexField,
                    Value(static_cast<long long>(applyOpsIndex())));
    newDoc.addField(DocumentSourceChangeStream::kApplyOpsTsField, Value(applyOpsTs()));

    // A prepared transaction carries its commit timestamp; emit it so the user-visible event
    // matches the transaction's CRUD events. An unprepared transaction has no commit timestamp.
    // The transform forwards the field only when the stream was opened with 'showCommitTimestamp'.
    if (_commitTimestamp) {
        newDoc.addField(DocumentSourceChangeStream::kCommitTimestampField,
                        Value(*_commitTimestamp));
    }

    return newDoc.freeze();
}

Document
ChangeStreamUnwindTransactionStage::TransactionOpIterator::_makeEndOfTransactionControlEvent()
    const {
    tassert(13875101,
            "expected endOfTransactionScopes metadata for a coordinated transaction",
            _endOfTransactionScopes);
    tassert(13875102,
            "expected the coordinated transaction to carry an lsid and txnNumber",
            _lsid && _txnNumber);

    // The event identifier repeats the transaction identity so that accounting records for
    // different shards that share a commit timestamp get distinct, deterministically ordered resume
    // tokens.
    MutableDocument operationDescription;
    operationDescription.addField(DocumentSourceChangeStream::kLsidField, Value(*_lsid));
    operationDescription.addField(DocumentSourceChangeStream::kTxnNumberField,
                                  Value(static_cast<long long>(*_txnNumber)));

    // The control event uses the same resume token as the user-visible event the router will
    // synthesize from it: the commit entry's timestamp and the reserved sentinel index.
    const ResumeTokenData resumeTokenData{_clusterTime,
                                          _changeStreamTokenVersion,
                                          kEndOfTransactionTxnOpIndex,
                                          boost::none,
                                          DocumentSourceChangeStream::kEndOfTransactionOpType,
                                          Value(),
                                          Value(operationDescription.freeze())};
    const Value resumeToken = Value(ResumeToken(resumeTokenData).toDocument());

    MutableDocument event;
    event.addField(DocumentSourceChangeStream::kIdField, resumeToken);
    event.metadata().setSortKey(resumeToken, /*isSingleElementKey=*/true);
    event.addField(DocumentSourceChangeStream::kOperationTypeField,
                   Value(DocumentSourceChangeStream::kEndOfTransactionOpType));
    event.addField(DocumentSourceChangeStream::kClusterTimeField, Value(_clusterTime));
    event.addField(DocumentSourceChangeStream::kWallTimeField, Value(_wallTime));
    if (_commitTimestamp) {
        event.addField(DocumentSourceChangeStream::kCommitTimestampField, Value(*_commitTimestamp));
    }
    event.addField(DocumentSourceChangeStream::kLsidField, Value(*_lsid));
    event.addField(DocumentSourceChangeStream::kTxnNumberField,
                   Value(static_cast<long long>(*_txnNumber)));
    event.addField(kEndOfTransactionScopesField, Value(*_endOfTransactionScopes));

    event.metadata().setChangeStreamControlEvent(
        DocumentMetadataFields::ChangeStreamControlEventType::kAccounting);

    return event.freeze();
}

boost::optional<Document>
ChangeStreamUnwindTransactionStage::TransactionOpIterator::_createEndOfTransactionIfNeeded() {
    // Capture the action; it is cleared once the event has been produced so that a later call (once
    // the transaction is exhausted) does not produce it again.
    const EndOfTransactionAction action = _endOfTransactionAction;
    if (action == EndOfTransactionAction::kNone) {
        return boost::none;
    }

    // A coordinated (multi-shard) transaction delivers its event to the router as an accounting
    // control event rather than a user-visible event. The router's synthesis stage turns it into
    // the user-visible 'endOfTransaction' event once the transaction completes for the watched
    // scope.
    if (action == EndOfTransactionAction::kEmitAccountingControlEvent) {
        _endOfTransactionAction = EndOfTransactionAction::kNone;
        return _makeEndOfTransactionControlEvent();
    }

    // A 'required' stream builds the event even for an ineligible transaction, to decide whether
    // the transaction touched the watched namespace and must therefore fail the stream. A
    // shard-local stream (a passthrough / direct-to-mongod stream) builds the user-visible event
    // for a coordinated transaction directly. '_makeEndOfTransactionDocument' consults
    // '_endOfTransactionAction', so build the document before clearing the action.
    const Document endOfTransaction = _makeEndOfTransactionDocument();
    _endOfTransactionAction = EndOfTransactionAction::kNone;

    const bool touchesWatchedNamespace =
        exec::matcher::matchesBSON(_endOfTransactionExpression.get(), endOfTransaction.toBson());

    if (action == EndOfTransactionAction::kFailIfIneligibleTouchesWatchedNamespace) {
        // The stream requires endOfTransaction events, but this transaction is ineligible: it
        // carries no 'allowEndOfTransaction' marker because the kill switch was off when it
        // committed. Fail only if the transaction touched the watched namespace.
        uassert(ErrorCodes::ChangeStreamFatalError,
                "The 'showEndOfTransaction' parameter to $changeStream was set to 'required', but "
                "no endOfTransaction event could be generated for a transaction that affects the "
                "stream's namespace, because the 'allowEndOfTransaction' server parameter was "
                "disabled when the transaction committed",
                !touchesWatchedNamespace);
        return boost::none;
    }

    return {touchesWatchedNamespace, endOfTransaction};
}

