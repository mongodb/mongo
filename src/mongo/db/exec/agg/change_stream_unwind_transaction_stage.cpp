boost::intrusive_ptr<exec::agg::Stage> documentSourceChangeStreamUnwindTransactionToStageFn(
    const boost::intrusive_ptr<DocumentSource>& documentSource) {
    auto* changeStreamUnwindTransactionDS =
        dynamic_cast<DocumentSourceChangeStreamUnwindTransaction*>(documentSource.get());

    tassert(10561305,
            "expected 'DocumentSourceChangeStreamUnwindTransaction' type",
            changeStreamUnwindTransactionDS);

    return make_intrusive<exec::agg::ChangeStreamUnwindTransactionStage>(
        changeStreamUnwindTransactionDS->kStageName,
        changeStreamUnwindTransactionDS->getExpCtx(),
        changeStreamUnwindTransactionDS->_filter.getOwned(),
        changeStreamUnwindTransactionDS->_expression);
}

namespace change_stream_filter {
/**
 * Builds the predicate that decides whether a synthesized endOfTransaction change event is
 * applicable to a change stream. It is evaluated against the event generated by
 * ChangeStreamUnwindTransactionStage for unprepared (single-shard or replica-set) transactions, and
 * never against oplog entries: for sharded transactions the event originates from a real
 * 'o2.endOfTransaction' oplog entry, whose namespace filtering is done by the oplog match filter in
 * buildTransactionFilter().
 *
 * Both the legacy and the 'featureFlagEndOfTransactionChangeEventSynthesis' behavior emit an
 * event only for a transaction that touched the stream's watched namespace, so both use the
 * 'o2.endOfTransaction' predicate. With 'kNone' no event is synthesized, so the predicate is never
 * consulted, unless the stream requires endOfTransaction events: a 'required' stream uses the
 * predicate to decide whether an ineligible transaction touches the watched namespace.
 */
std::unique_ptr<MatchExpression> buildEndOfTransactionFilter(
    const boost::intrusive_ptr<ExpressionContext>& expCtx,
    change_stream::EndOfTransactionBehavior behavior,
    exec::agg::EndOfTransactionMode mode) {
    if (behavior == change_stream::EndOfTransactionBehavior::kNone &&
        mode != exec::agg::EndOfTransactionMode::kRequired) {
        return std::make_unique<AlwaysTrueMatchExpression>();
    }

    auto nsRegex = DocumentSourceChangeStream::getNsRegexForChangeStream(expCtx);
    return std::make_unique<RegexMatchExpression>("o2.endOfTransaction"sv, nsRegex, /*options=*/"");
}
}  // namespace change_stream_filter

