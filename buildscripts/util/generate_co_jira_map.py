#!/usr/bin/env python3
"""
Regenerate `buildscripts/util/co_jira_map.yml`, which maps the GitHub teams that
appear in `.github/CODEOWNERS` to their JIRA "Assigned Teams" value.

The JIRA team names come from the team registry in https://github.com/10gen/mothra,
which is also what foliage uses to route build failures. Mothra is not vendored into
this repo; clone it next to the repo root (or pass `--mothra-teams`) before running:

    git clone --depth=1 git@github.com:10gen/mothra.git mothra
    python3 buildscripts/util/generate_co_jira_map.py
"""

import argparse
import glob
import os
import sys

import yaml
from codeowners import CodeOwners

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CODEOWNERS_FILE = os.path.join(REPO_ROOT, ".github", "CODEOWNERS")
CO_JIRA_MAP_FILE = os.path.join(REPO_ROOT, "buildscripts", "util", "co_jira_map.yml")
DEFAULT_MOTHRA_TEAMS = os.path.join(REPO_ROOT, "mothra", "mothra", "teams")

# Mothra team names that are not valid options for the "Assigned Teams" field
# (customfield_12751), verified against the SERVER project. Tickets created with
# these values are rejected, so treat the teams as unmapped instead.
NOT_A_JIRA_OPTION = {
    "Product Security Server Team",
    "Secure SDLC",
}

# JIRA teams that were renamed after mothra last recorded them, so mothra still
# reports the old name, which is no longer a valid option. Drop an entry once mothra
# catches up.
RENAMED_JIRA_TEAMS = {
    "Query Integration": "DB Integration & Observability",  # SERVER-135794
}

HEADER = """# Maps GitHub teams that appear as CODEOWNERS to their JIRA "Assigned Teams" value.
#
# Generated by buildscripts/util/generate_co_jira_map.py -- do not edit by hand.
#
# Values come from the team registry in https://github.com/10gen/mothra: each entry is
# a team's `assigned_jira_triage_team_name`, falling back to its `name`, keyed by every
# `code_owners.github_teams[].team_name` it claims. This is the same data foliage uses
# to route build failures.
#
# A null value means the GitHub team has no usable JIRA team: either mothra does not
# know the team, or its JIRA name is not a valid "Assigned Teams" option. Consumers
# should treat those as unowned and fall back to their own default.
"""


def github_teams_from_codeowners(codeowners_contents: str) -> set[str]:
    """Return every GitHub team named as an owner in a CODEOWNERS file."""
    return {
        owner.removeprefix("@")
        for _, _, owners, _, _ in CodeOwners(codeowners_contents).paths
        for owner_type, owner in owners
        if owner_type == "TEAM"
    }


def jira_teams_from_mothra(teams_dir: str) -> dict[str, str]:
    """Map each GitHub team claimed in mothra to the JIRA team that owns it."""
    team_files = sorted(glob.glob(os.path.join(teams_dir, "*.yaml")))
    if not team_files:
        raise SystemExit(f"No mothra team files found in {teams_dir}; see --help.")

    jira_teams = {}
    for team_file in team_files:
        with open(team_file, "r", encoding="utf8") as f:
            contents = yaml.safe_load(f) or {}
        for team in contents.get("teams", []):
            # `name` is the JIRA team unless the team triages under a different one.
            jira_team = team.get("assigned_jira_triage_team_name") or team.get("name")
            for github_team in (team.get("code_owners") or {}).get("github_teams", []) or []:
                github_team_name = github_team.get("team_name")
                if not github_team_name or not jira_team:
                    continue
                previous = jira_teams.setdefault(github_team_name, jira_team)
                if previous != jira_team:
                    print(
                        f"WARNING: {github_team_name} is claimed by both '{previous}' and"
                        f" '{jira_team}' in mothra; keeping '{previous}'.",
                        file=sys.stderr,
                    )
    return jira_teams


def build_map(
    github_teams: set[str], mothra_teams: dict[str, str], previous: dict[str, list[str] | None]
) -> dict[str, tuple[list[str | None], str]]:
    """
    Map every GitHub team to its JIRA team, keyed by team, with a trailing comment.

    Teams mothra does not know keep whatever they were mapped to by hand, so
    regenerating never silently drops a curated entry.
    """
    result = {}
    for github_team in sorted(github_teams | set(previous)):
        jira_team = mothra_teams.get(github_team)
        jira_team = RENAMED_JIRA_TEAMS.get(jira_team, jira_team)
        comment = ""

        if jira_team in NOT_A_JIRA_OPTION:
            comment = f" # mothra says '{jira_team}', which is not a valid JIRA option."
            jira_team = None
        elif jira_team is None:
            hand_mapped = [team for team in previous.get(github_team) or [] if team]
            if hand_mapped:
                result[github_team] = (hand_mapped, " # Not in mothra; mapped by hand.")
                continue
            comment = " # Not in mothra."

        result[github_team] = ([jira_team], comment)
    return result


def render(co_jira_map: dict[str, tuple[list[str | None], str]]) -> str:
    lines = [HEADER]
    for github_team, (jira_teams, comment) in co_jira_map.items():
        lines.append(f"{github_team}:{comment}")
        lines.extend(f"  - {jira_team if jira_team else '~'}" for jira_team in jira_teams)
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--mothra-teams",
        default=DEFAULT_MOTHRA_TEAMS,
        help=f"Directory holding mothra's team YAML files (default: {DEFAULT_MOTHRA_TEAMS})",
    )
    args = parser.parse_args()

    with open(CODEOWNERS_FILE, "r", encoding="utf8") as f:
        github_teams = github_teams_from_codeowners(f.read())
    with open(CO_JIRA_MAP_FILE, "r", encoding="utf8") as f:
        previous = yaml.safe_load(f) or {}

    mothra_teams = jira_teams_from_mothra(args.mothra_teams)
    co_jira_map = build_map(github_teams, mothra_teams, previous)

    with open(CO_JIRA_MAP_FILE, "w", encoding="utf8") as f:
        f.write(render(co_jira_map))

    unmapped = sorted(team for team, (teams, _) in co_jira_map.items() if teams == [None])
    print(f"Wrote {len(co_jira_map)} teams to {CO_JIRA_MAP_FILE}, {len(unmapped)} unmapped:")
    for team in unmapped:
        print(f"  {team}")


if __name__ == "__main__":
    main()
