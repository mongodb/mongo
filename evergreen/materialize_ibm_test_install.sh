#!/usr/bin/env bash

# Materialize install targets for IBM cross-compile test tasks.
#
# Evergreen compile task groups run their members on one host, but each task can receive a fresh
# work directory. The compile task's local MongoInstallRule output therefore is not guaranteed to
# be present when a later resmoke task starts. Rebuilding the small install target here is cheap on
# RBE-enabled variants: compiler actions hit the remote cache, while the native install action
# recreates the local convenience tree needed by resmoke.

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" >/dev/null 2>&1 && pwd)"
. "$DIR/prelude.sh"
. "$DIR/bazel_evergreen_shutils.sh"

set -o errexit
set -o pipefail

target="${1:-}"
case "$target" in
install-dbtest)
    expected="bazel-bin/install/bin/dbtest"
    private_expected="bazel-bin/install-dbtest/bin/dbtest"
    bazel_args="--config=evg"
    ;;
install-mongo_integration_test)
    expected="bazel-bin/install/install-mongo_integration_test_test_list.txt"
    private_expected="bazel-bin/install-mongo_integration_test/install-mongo_integration_test_test_list.txt"
    bazel_args="--config=evg --include_autogenerated_targets=True"
    ;;
*)
    echo "Unknown IBM test install target: ${target:-<missing>}" >&2
    exit 2
    ;;
esac

# This helper is intentionally a no-op outside the IBM cross variants. Other platforms already
# download their test artifacts through the normal Evergreen setup path.
if [[ "${bazel_compile_flags:-}" != *"--config=linux-ppc64le-"*cross-rbe* &&
    "${bazel_compile_flags:-}" != *"--config=linux-s390x-"*cross-rbe* ]]; then
    exit 0
fi

if [[ -e "src/$expected" ]]; then
    echo "IBM test install output already exists: src/$expected"
    exit 0
fi

bazel_evergreen_shutils::activate_and_cd_src
bazel_evergreen_shutils::export_ssl_paths_if_needed

BAZEL_BINARY="$(bazel_evergreen_shutils::bazel_get_binary_path)"
export BAZEL_BINARY

declare -a flags=($bazel_args)
local_arg="$(bazel_evergreen_shutils::compute_local_arg build)"
if [[ -n "$local_arg" ]]; then
    declare -a local_flags
    read -r -a local_flags <<<"$local_arg"
    flags+=("${local_flags[@]}")
fi
if [[ -n "${version:-}" ]]; then
    flags+=("--define=MONGO_VERSION=${version}")
fi
# Evergreen expansions are authored as Bazel command-line words. Keep the same word splitting
# used by bazel_compile.sh while avoiding eval of the complete command. Include task and patch
# flags as well so this materialization has the same target configuration as compile_dbtest or
# compile_integration_test.
append_flags() {
    local flag_string="${1:-}"
    [[ -n "$flag_string" ]] || return 0
    local -a extra_flags
    read -r -a extra_flags <<<"$flag_string"
    flags+=("${extra_flags[@]}")
}

append_flags "${bazel_compile_flags:-}"
append_flags "${task_compile_flags:-}"
append_flags "${integration_test_compile_flags:-}"
append_flags "${patch_compile_flags:-}"

echo "Materializing IBM test install target ${target} with ${BAZEL_BINARY}"
export MONGO_BAZEL_INSTALL_TARGET="$target"
export RETRY_ON_FAIL=1
bazel_evergreen_shutils::retry_bazel_cmd 3 "$BAZEL_BINARY" build "${flags[@]}" "$target"

if [[ ! -e "$expected" ]]; then
    # The wrapper normally points bazel-bin/install at the shared install tree. If another
    # install target populated that tree first, retain the target-specific convenience link so
    # the generated test list and its binaries resolve from this task.
    if [[ -e "$private_expected" ]]; then
        if [[ -L bazel-bin/install ]]; then
            rm bazel-bin/install
            ln -s "$target" bazel-bin/install
        elif [[ ! -e bazel-bin/install ]]; then
            ln -s "$target" bazel-bin/install
        fi
    fi
fi

if [[ ! -e "$expected" ]]; then
    echo "IBM test install target completed without expected output: $expected" >&2
    exit 1
fi
